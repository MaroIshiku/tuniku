export type TranslationKey = keyof typeof en;
type ContextValue = { language: Language; setLanguage: (language: Language) => void; t: (key: TranslationKey) => string };
const I18nContext = createContext<ContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");
  const value = useMemo<ContextValue>(() => ({
    language,
    setLanguage: (next) => {
      localStorage.setItem("tuniku-language", "en");
      document.documentElement.lang = "en";
      setLanguageState(next);
    },
    t: (key) => en[key]
  }), [language]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): ContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("I18nProvider is missing.");
  return value;
}
